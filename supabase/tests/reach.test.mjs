await as(ana);
ok("RSVPs are visible only to the person", (await q(`select * from event_rsvps`)).length === 1);
ok("list shows counts and my RSVP", (await q(`select rsvp_count, going from list_events('webinar', false)`))[0].going === true);
await db.exec(`select rsvp_event('${ev}', false)`);
await as(cara);
ok("a freed place can be taken", (await fails(`select rsvp_event('${ev}', true)`)) === null);
await as(boss);
await db.exec(`select exhibit_at_event('${fair}', true)`);
ok("verified company can exhibit at a career fair", (await q(`select * from event_exhibitor_list('${fair}')`)).length === 1);
ok("cannot exhibit at a webinar", (await fails(`select exhibit_at_event('${ev}', true)`)) !== null);
await as(ana);
ok("a candidate cannot exhibit", (await fails(`select exhibit_at_event('${fair}', true)`)) !== null);
await as(boss);
await db.exec(`select cancel_event('${ev}')`);
await as(cara);
ok("attendees are told about a cancellation", (await q(`select 1 from notifications where user_id='${cara}' and title like '%cancelled%'`)).length === 1);
ok("cancelled events disappear from the list", (await q(`select * from list_events(null, false)`)).length === 1);
await as(ben);
ok("others cannot cancel an event", (await fails(`select cancel_event('${fair}')`)) !== null);

