await as(boss);
ok("an event needs a venue or link", (await fails(`select create_event('event', 'Nowhere', null, ${future}, null, null, null)`))?.includes("venue") ?? false);
ok("events in the past are refused", (await fails(`select create_event('event', 'Old news', null, now() - interval '3 days', null, 'Harare', null)`)) !== null);
await as(admin);
const fair = (await q(`select create_event('career_fair', 'Harare Career Fair', 'Meet employers', ${future} + interval '10 days', null, 'Harare ICC', null) id`))[0].id;
ok("admin can host a career fair", !!fair);
await as(null, "anon");
