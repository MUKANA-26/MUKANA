ok("blocked member cannot message", (await fails(`select start_direct_conversation('${dan}')`)) !== null);
ok("blocked member absent from search", (await q(`select * from search_people('Dan')`)).length === 0);
await as(dan);
ok("blocker also sees nothing of the blocked one", (await q(`select get_person('${ben}') p`))[0].p === null);
await db.exec(`delete from blocks where blocker_id='${dan}'`);

console.log("\n== messaging");
await as(ana);
ok("cannot message someone you are not connected with", (await fails(`select start_direct_conversation('${dan}')`))?.includes("connect") ?? false);
const conv = (await q(`select start_direct_conversation('${ben}') id`))[0].id;
ok("direct conversation with a connection", !!conv);
ok("same conversation is reused", (await q(`select start_direct_conversation('${ben}') id`))[0].id === conv);
await db.exec(`select send_message('${conv}', 'Hi Ben!')`);
await db.exec(`select send_message('${conv}', 'Are you free to study tomorrow?')`);
await as(ben);
ok("recipient has 1 unread conversation", (await q(`select unread_message_count() n`))[0].n === 1);
ok("only one notification per unread conversation", (await q(`select count(*)::int n from notifications where user_id='${ben}' and type::text='message'`))[0].n === 1);
