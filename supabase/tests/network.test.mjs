await db.exec(`update candidate_profiles set institution='University of Zimbabwe', programme='BSc Computer Science', skills=array['Python','SQL','Excel'], bio='Student', province='Harare' where user_id in ('${ana}','${ben}')`);
await db.exec(`update profiles set headline='Aspiring data analyst' where id='${ana}'`);

