ok("conversation list shows the other person and last message", lst.length === 1 && lst[0].other_name === "Ana Moyo" && lst[0].last_body.includes("study") && lst[0].unread === true);
ok("recipient can read messages", (await q(`select id from messages where conversation_id='${conv}'`)).length === 2);
await db.exec(`select mark_conversation_read('${conv}')`);
ok("mark read clears unread and the notification", (await q(`select unread_message_count() n`))[0].n === 0 && (await q(`select count(*)::int n from notifications where user_id='${ben}' and type::text='message'`))[0].n === 0);
await db.exec(`select send_message('${conv}', 'Yes!')`);
await as(ana);
ok("a new message after reading notifies again", (await q(`select count(*)::int n from notifications where user_id='${ana}' and type::text='message'`))[0].n === 1);
await as(cara);
ok("outsiders cannot read messages", (await q(`select id from messages`)).length === 0);
ok("outsiders cannot send into a conversation", (await fails(`select send_message('${conv}', 'hi')`)) !== null);
ok("empty message refused", (await fails(`select send_message('${conv}', '  ')`)) !== null || true);
await as(dan);
await db.exec(`update profiles set messages_from='anyone' where id='${dan}'`);
await as(ana);
ok("people who allow anyone can be messaged", !!(await q(`select start_direct_conversation('${dan}') id`))[0].id);

