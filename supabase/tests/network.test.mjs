ok("duplicate request refused", (await fails(`select connect_request('${ben}')`))?.includes("pending") ?? false);
ok("direct write to connections refused", (await fails(`insert into connections (requester_id, addressee_id) values ('${ana}','${cara}')`)) !== null);
await as(ben);
ok("addressee is notified", (await q(`select title from notifications where user_id='${ben}' and type::text='network'`)).some((n) => n.title.includes("wants to connect")));
ok("invitations list shows the request", (await q(`select * from list_connections('received')`)).length === 1);
await as(cara);
ok("third party cannot accept", (await fails(`select connection_respond('${c1}', true)`)) !== null);
await as(ben);
await db.exec(`select connection_respond('${c1}', true)`);
ok("accepted: both are connected", (await q(`select are_connected('${ana}','${ben}') v`))[0].v === true);
await as(ana);
ok("requester told about acceptance", (await q(`select 1 from notifications where user_id='${ana}' and title like '%accepted your connection%'`)).length === 1);
ok("already connected refused", (await fails(`select connect_request('${ben}')`))?.includes("already") ?? false);
await as(cara);
await db.exec(`select connect_request('${ana}')`);
await as(ana);
await db.exec(`select connect_request('${cara}')`); // they asked first: replying connects
ok("mutual request auto-accepts", (await q(`select are_connected('${ana}','${cara}') v`))[0].v === true);
await db.exec(`select connection_remove('${cara}')`);
ok("disconnect removes the connection", (await q(`select are_connected('${ana}','${cara}') v`))[0].v === false);

console.log("\n== follow, block");
await as(ben);
await db.exec(`insert into follows (follower_id, followee_id) values ('${ben}', '${dan}')`);
await as(dan);
ok("followee notified", (await q(`select 1 from notifications where user_id='${dan}' and title like '%started following you%'`)).length === 1);
ok("cannot follow as someone else", (await fails(`insert into follows (follower_id, followee_id) values ('${ana}', '${dan}')`)) !== null);
await db.exec(`insert into blocks (blocker_id, blocked_id) values ('${dan}', '${ben}')`);
ok("block removes the follow", (await q(`select count(*)::int n from follows`))[0].n === 0);
await as(ben);
ok("blocked member cannot connect", (await fails(`select connect_request('${dan}')`)) !== null);
ok("blocked member cannot follow", (await fails(`insert into follows (follower_id, followee_id) values ('${ben}', '${dan}')`)) !== null);
